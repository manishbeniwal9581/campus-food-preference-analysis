export function buildInitialSurveys(anchorDateIso = '2026-11-19T11:00:00.000Z'): SurveyResponse[] {
  const anchor = new Date(anchorDateIso).getTime();
  return RAW_SURVEY_SEEDS.map((seed, idx) => {
    const overall = Number(
      ((seed.qualityRating + seed.tasteRating + seed.hygieneRating) / 3).toFixed(2)
    );
    const createdAt = new Date(
      anchor - seed.daysAgo * 24 * 60 * 60 * 1000 - (idx % 6) * 42 * 60 * 1000
    ).toISOString();

    return {
      id: `demo-survey-${String(idx + 1).padStart(3, '0')}`,
      studentName: seed.studentName,
      department: seed.department,
      semester: seed.semester,
      preferredCategory: seed.preferredCategory,
      favouriteItem: seed.favouriteItem,
      priceRange: seed.priceRange,
      qualityRating: seed.qualityRating,
      tasteRating: seed.tasteRating,
      hygieneRating: seed.hygieneRating,
      overallRating: overall,
      suggestions: seed.suggestions,
      createdAt,
      isDemo: true,
      feedbackStatus: seed.feedbackStatus,
    };
  });
}

